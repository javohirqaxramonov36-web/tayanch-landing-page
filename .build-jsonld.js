#!/usr/bin/env node
/* =========================================================================
   .build-jsonld.js — Schema.org "Course" JSON-LD generator
   -------------------------------------------------------------------------
   Kurslar ro'yxati YAGONA manbadan (courses-data.js) olinadi, shuning uchun
   katalogga kurs qo'shilsa/yoki o'chirilsa JSON-LD ham avtomatik yangilanadi
   va haqiqiy katalog bilan hech qachon ziddiyatga tushmaydi.

   Ishlatish:  node .build-jsonld.js

   Natija: courses.html ichidagi
     <!-- BEGIN:COURSE-JSONLD --> ... <!-- END:COURSE-JSONLD -->
   bloki qayta yoziladi (idempotent — qayta-qayta ishga tushirish xavfsiz).
   ========================================================================= */
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = __dirname;
const CANON = 'https://javohirqaxramonov36-web.github.io/tayanch-landing-page/';

/* --- 1. courses-data.js ni brauzersiz (Node) muhitda yuklash --- */
const sandbox = {
  window: {},
  document: {
    readyState: 'loading',
    addEventListener: () => {},
    querySelectorAll: () => [],
    getElementById: () => null,
    documentElement: { setAttribute: () => {} }
  },
  console
};
sandbox.window = sandbox;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'courses-data.js'), 'utf8'), sandbox);

const api = sandbox.TayanchCourses;
if (!api || !Array.isArray(api.data)) {
  console.error('XATO: courses-data.js dan TayanchCourses.data olinmadi');
  process.exit(1);
}
const COURSES = api.data;

/* --- 2. Har bir kurs uchun Schema.org Course obyekti --- */
const CAT_SLUG = { ai: 'ai', ielts: 'ielts', admission: 'admission' };

function courseNode(c) {
  return {
    '@type': 'Course',
    '@id': `${CANON}courses.html#course-${c.id}`,
    name: c.title,
    description: c.desc,
    provider: {
      '@type': 'Organization',
      name: 'Tayanch Educational Platform',
      sameAs: CANON
    },
    educationalLevel: c.level,
    inLanguage: 'uz',
    isAccessibleForFree: true,
    url: `${CANON}courses.html#course-${c.id}`,
    about: c.catName,
    offers: {
      '@type': 'Offer',
      price: '0',
      priceCurrency: 'UZS',
      availability: 'https://schema.org/InStock',
      url: `${CANON}courses.html#course-${c.id}`
    },
    hasCourseInstance: {
      '@type': 'CourseInstance',
      courseMode: 'online',
      courseWorkload: c.duration
    }
  };
}

const graph = COURSES.map(courseNode);
graph.push({
  '@type': 'ItemList',
  '@id': `${CANON}courses.html#courselist`,
  name: `Tayanch — ${COURSES.length} ta bepul kurslar katalogi`,
  numberOfItems: COURSES.length,
  itemListElement: COURSES.map((c, i) => ({
    '@type': 'ListItem',
    position: i + 1,
    item: { '@id': `${CANON}courses.html#course-${c.id}` }
  }))
});

const jsonld = {
  '@context': 'https://schema.org',
  '@graph': graph
};

const block =
  '    <!-- BEGIN:COURSE-JSONLD -->\n' +
  '    <!-- AUTO-GENERATED by .build-jsonld.js from courses-data.js — qo\'lda tahrirlamang -->\n' +
  '    <script type="application/ld+json">\n' +
  JSON.stringify(jsonld, null, 2).split('\n').map(l => (l ? '  ' + l : l)).join('\n') +
  '\n    </script>\n' +
  '    <!-- END:COURSE-JSONLD -->';

/* --- 3. courses.html ichiga inject qilish --- */
const FILE = path.join(ROOT, 'courses.html');
let html = fs.readFileSync(FILE, 'utf8');
const BEGIN = '    <!-- BEGIN:COURSE-JSONLD -->';
const END = '    <!-- END:COURSE-JSONLD -->';

const anchor = '    <!-- Fonts & Icons -->';
if (html.includes(BEGIN) && html.includes(END)) {
  const s = html.indexOf(BEGIN);
  const e = html.indexOf(END) + END.length;
  html = html.slice(0, s) + block + html.slice(e);
  console.log('courses.html: mavjud JSON-LD bloki yangilandi');
} else if (html.includes(anchor)) {
  html = html.replace(anchor, block + '\n\n' + anchor);
  console.log('courses.html: JSON-LD bloki qo\'shildi');
} else {
  console.error('XATO: courses.html ichida anchor topilmadi');
  process.exit(1);
}

fs.writeFileSync(FILE, html, 'utf8');
console.log(`OK — ${COURSES.length} ta kurs uchun Course JSON-LD yozildi (jami ${COURSES.length} ta Course + 1 ta ItemList)`);
